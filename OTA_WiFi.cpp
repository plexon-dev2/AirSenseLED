#define OTA_WIFI_VERSION  "1.1"

/* MQTT OTA topic — device subscribes to this for remote OTA commands */
#define OTA_MQTT_COMMAND_TOPIC   "aqi/" WIFI_MQTT_CLIENT_ID "/ota/command"
#define OTA_MQTT_STATUS_TOPIC    "aqi/" WIFI_MQTT_CLIENT_ID "/ota/status"

static WebServer  s_server(OTA_WIFI_HTTP_PORT);
static bool       s_serverStarted = false;

/* ?????? GET /status ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void _handle_status(void)
{
    char buf[256];
    snprintf(buf, sizeof(buf),
        "{\"version\":\"%s\",\"project\":\"AirSense\","
        "\"ip\":\"%s\",\"free_heap\":%lu,"
        "\"uptime_s\":%lu,\"partition\":\"%s\"}",
        OTA_WIFI_VERSION, WIFI_STATIC_IP,
        (unsigned long)esp_get_free_heap_size(),
        (unsigned long)(millis() / 1000UL),
        esp_ota_get_running_partition()->label);
    s_server.sendHeader("Access-Control-Allow-Origin", "*");
    s_server.send(200, "application/json", buf);
}

/* ?????? GET /ota_start ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
 *
 * Reboots device into factory partition (OTA receiver firmware).
 * Factory receiver then accepts firmware push on port 8080.
 *
 * Python GUI calls this, waits 8s, then pushes to port 8080.
 * ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void _handle_ota_start(void)
{
    /* Find factory partition */
    const esp_partition_t* factory = esp_partition_find_first(
        ESP_PARTITION_TYPE_APP,
        ESP_PARTITION_SUBTYPE_APP_FACTORY,
        NULL);

    if (!factory) {
        Serial.println("[OTA_WiFi] ERROR: factory partition not found!");
        s_server.send(500, "application/json",
                      "{\"error\":\"factory partition not found\"}");
        return;
    }

    Serial.printf("[OTA_WiFi] Factory partition: %s at 0x%08lx\n",
                  factory->label, (unsigned long)factory->address);

    /* Set factory as next boot target */
    const esp_partition_t* otadata = esp_partition_find_first(ESP_PARTITION_TYPE_DATA, ESP_PARTITION_SUBTYPE_DATA_OTA, NULL);
    if (!otadata) { s_server.send(500, "application/json", "{\"error\":\"otadata not found\"}"); return; }
    esp_partition_erase_range(otadata, 0, otadata->size);
    Serial.println("[OTA_WiFi] otadata erased - factory will boot next");

    Serial.println("[OTA_WiFi] Rebooting to factory OTA receiver...");
    Serial.println("[OTA_WiFi] Factory will accept firmware on port 8080");

    s_server.sendHeader("Access-Control-Allow-Origin", "*");
    s_server.send(200, "application/json",
                  "{\"status\":\"rebooting\","
                  "\"message\":\"Switching to OTA receiver on port 8080\","
                  "\"ota_port\":8080}");

    delay(1000);
    esp_restart();
}

/* ?????? POST /restart ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void _handle_restart(void)
{
    s_server.send(200, "application/json", "{\"status\":\"restarting\"}");
    delay(500);
    esp_restart();
}


/* ─── MQTT OTA Handler ─────────────────────────────────────────────────────
 *
 * Called by WiFiComm when a message arrives on the OTA command topic.
 * Expected payload: {"url":"https://...firmware.bin","version":"1.5.0"}
 *
 * ────────────────────────────────────────────────────────────────────────── */
void OTA_WiFi__MQTTOTAHandler(const char *topic, const char *payload, uint16_t length)
{
    (void)topic;
    (void)length;

    Serial.printf("[OTA_WiFi] MQTT OTA command received: %s\n", payload);

    /* Parse URL from JSON payload */
    String p = String(payload);
    int urlStart = p.indexOf("\"url\":");
    if (urlStart < 0)
    {
        Serial.println("[OTA_WiFi] MQTT OTA: no url field in payload");
        return;
    }
    int q1 = p.indexOf('"', urlStart + 6);
    int q2 = p.indexOf('"', q1 + 1);
    if (q1 < 0 || q2 < 0)
    {
        Serial.println("[OTA_WiFi] MQTT OTA: malformed url field");
        return;
    }
    String url = p.substring(q1 + 1, q2);
    Serial.printf("[OTA_WiFi] MQTT OTA: downloading from %s\n", url.c_str());

    /* Publish status: starting */
    extern WiFiComm_Status WiFiComm__MQTTPublish(const char*, const char*);
    WiFiComm__MQTTPublish(OTA_MQTT_STATUS_TOPIC,
        "{\"status\":\"downloading\",\"source\":\"mqtt\"}");

    /* Perform OTA update */
    WiFiClient client;
    httpUpdate.rebootOnUpdate(false);

    t_httpUpdate_return ret = httpUpdate.update(client, url);

    switch (ret)
    {
        case HTTP_UPDATE_OK:
            Serial.println("[OTA_WiFi] MQTT OTA: success — rebooting");
            WiFiComm__MQTTPublish(OTA_MQTT_STATUS_TOPIC,
                "{\"status\":\"success\",\"source\":\"mqtt\"}");
            delay(1000U);
            ESP.restart();
            break;
        case HTTP_UPDATE_FAILED:
            Serial.printf("[OTA_WiFi] MQTT OTA: failed — %s\n",
                httpUpdate.getLastErrorString().c_str());
            WiFiComm__MQTTPublish(OTA_MQTT_STATUS_TOPIC,
                "{\"status\":\"failed\",\"source\":\"mqtt\"}");
            break;
        case HTTP_UPDATE_NO_UPDATES:
            Serial.println("[OTA_WiFi] MQTT OTA: no update available");
            break;
        default:
            break;
    }
}

/* Returns the MQTT OTA command topic string */
const char* OTA_WiFi__GetMQTTCommandTopic(void)
{
    return OTA_MQTT_COMMAND_TOPIC;
}

/* ?????? Public API ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
void OTA_WiFi__Init(void)
{
    s_server.on("/status",    HTTP_GET,  _handle_status);
    s_server.on("/ota_start", HTTP_GET,  _handle_ota_start);
    s_server.on("/restart",   HTTP_POST, _handle_restart);

    Serial.printf("[OTA_WiFi] Ready ??? http://%s:%d\n",
                  WIFI_STATIC_IP, (int)OTA_WIFI_HTTP_PORT);
    Serial.printf("[OTA_WiFi] To update: GET /ota_start ??? push to port 8080\n");
}

void OTA_WiFi__Handler(void)
{
    if (!s_serverStarted && (WiFi.status() == WL_CONNECTED)) {
        s_server.begin();
        s_serverStarted = true;
        Serial.printf("[OTA_WiFi] HTTP server started port %d\n",
                      (int)OTA_WIFI_HTTP_PORT);
        if (MDNS.begin("airsense")) {
            MDNS.addService("http", "tcp", OTA_WIFI_HTTP_PORT);
            Serial.println("[OTA_WiFi] mDNS started — airsense.local");
        }
    }
    if (s_serverStarted)
        s_server.handleClient();
}

